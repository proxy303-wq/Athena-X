from pydantic import BaseModel


class TradePlan(BaseModel):

    # --------------------------------------------------------
    # Decision
    # --------------------------------------------------------

    direction: str

    confidence: float

    # --------------------------------------------------------
    # Classification
    # --------------------------------------------------------

    trend: str

    setup: str

    risk: str

    # --------------------------------------------------------
    # Trade Levels
    # --------------------------------------------------------

    entry: float

    stop_loss: float

    target1: float

    target2: float

    # --------------------------------------------------------
    # Explanation
    # --------------------------------------------------------

    reasoning: list[str]